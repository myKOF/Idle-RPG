'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const cfg=require('../tools/config_tables.cjs');
const data=fs.readFileSync(require.resolve('../js/data.js'),'utf8');
const bosses=cfg.evalLiteral(cfg.extractLiteral(data,'BOSS_LIST').literal);
test('first tower boss becomes Skeleton King without changing stats; floor 11 uses its own row with the same look',()=>{
  const stats={level:5,hp:1234,atk:45,def:23,mdef:15,aspd:.8,dodge:4,hit:95,xp:12};
  const context={BOSS_LIST:bosses,STR:(_id,floor,name)=>floor+' '+name,bossStatsFor:()=>stats,
    towerBossDefFor:f=>bosses[(f-1)%bosses.length],
    npcCombatProfile:(bd)=>({aspd:bd.atkSpeed,runSpeed:0,atkRange:0,sightRange:50}),ELEMENTS:['fire']};
  vm.runInNewContext(fs.readFileSync(require.resolve('../js/tower.js'),'utf8'),context);
  const boss=context.makeBoss(1);
  assert.match(boss.name,/骷髏王/);
  assert.equal(boss.npcId,'tower_boss_1');
  assert.equal(boss.model3d.file,'images/models/npc3d/boss1.glb');
  assert.equal(boss.maxHp,stats.hp);assert.equal(boss.atk,stats.atk);assert.equal(boss.aspd,bosses[0].atkSpeed);
  assert.equal(context.makeBoss(2).model3d.file,'images/models/npc3d/treant.glb');
  assert.equal(context.makeBoss(2).maxHp,stats.hp);
  assert.equal(context.makeBoss(2).aspd,bosses[1].atkSpeed);
  const third=context.makeBoss(3);
  assert.equal(third.model3d.file,'images/models/npc3d/boss3_character.glb');
  assert.equal(third.model3d.clips.walk,'Running');
  assert.equal(third.model3d.clips.attack1,'Basic_Jump');
  assert.equal(third.model3d.clips.die,'Shot_and_Fall_Forward');
  assert.equal(third.name,'3 骷髏王Ⅲ');
  assert.equal(third.maxHp,stats.hp);assert.equal(third.aspd,bosses[2].atkSpeed);
  assert.equal(context.makeBoss(13).model3d.file,'images/models/npc3d/boss3_character_lv2.glb');
  assert.equal(context.makeBoss(13).name,'13 雷霆巨獸','the existing configured name remains');
  assert.deepEqual(context.makeBoss(13).model3d.clips,third.model3d.clips);
  assert.equal(context.makeBoss(63).model3d.file,'images/models/npc3d/boss3_character_lv2.glb');
  assert.equal(context.makeBoss(113).model3d.file,'images/models/npc3d/boss3_character_lv2.glb');
  assert.equal(context.makeBoss(23).model3d.file,'images/models/npc3d/boss3_character_lv3.glb');
  assert.equal(context.makeBoss(23).name,'23 雷霆巨獸','the existing configured name remains');
  assert.deepEqual(context.makeBoss(23).model3d.clips,third.model3d.clips);
  assert.equal(context.makeBoss(73).model3d.file,'images/models/npc3d/boss3_character_lv3.glb');
  assert.equal(context.makeBoss(123).model3d.file,'images/models/npc3d/boss3_character_lv3.glb');
  assert.equal(context.makeBoss(33).model3d,null,'other independent rows retain their appearance');
  for(const [f,id,file] of [[5,'tower_boss_5','boss5'],[55,'tower_boss_5','boss5'],[105,'tower_boss_5','boss5'],[15,'tower_boss_15','boss5_lv2'],[65,'tower_boss_15','boss5_lv2'],[115,'tower_boss_15','boss5_lv2'],[25,'tower_boss_25','boss5_lv3'],[75,'tower_boss_25','boss5_lv3'],[125,'tower_boss_25','boss5_lv3']]){
    const b=context.makeBoss(f);
    assert.equal(b.npcId,id);
    assert.equal(b.model3d.file,'images/models/npc3d/'+file+'.glb');
    assert.deepEqual(b.model3d.clips,{idle:'Walk',walk:'Walk',attack1:'Attack1',attack2:'Attack2',attack3:'Attack3',die:'Die'});
    assert.equal(b.aspd,bosses[(f-1)%50].atkSpeed,'stats and skills are untouched by the new look');
  }
  assert.equal(context.makeBoss(35).model3d,null,'the other poison rows keep their previous appearance');
  assert.equal(context.makeBoss(53).model3d.file,third.model3d.file);
  assert.equal(context.makeBoss(103).model3d.file,third.model3d.file);
  assert.equal(context.makeBoss(12).npcId,'tower_boss_12');
  assert.equal(context.makeBoss(12).model3d.file,'images/models/npc3d/treant_lv2.glb');
  assert.equal(context.makeBoss(12).name,'12 樹人Ⅱ');
  assert.equal(context.makeBoss(62).model3d.file,'images/models/npc3d/treant_lv2.glb');
  assert.equal(context.makeBoss(112).model3d.file,'images/models/npc3d/treant_lv2.glb');
  assert.equal(context.makeBoss(22).model3d.file,'images/models/npc3d/treant_lv3.glb');
  assert.equal(context.makeBoss(22).name,'22 樹人Ⅲ');
  assert.equal(context.makeBoss(72).model3d.file,'images/models/npc3d/treant_lv3.glb');
  assert.equal(context.makeBoss(122).model3d.file,'images/models/npc3d/treant_lv3.glb');
  assert.equal(context.makeBoss(32).model3d.file,'images/models/npc3d/boss2.glb','other independent rows retain their previous appearance');
  assert.equal(context.makeBoss(2).name,'2 樹人');
  const f11=context.makeBoss(11);
  assert.equal(f11.npcId,'tower_boss_11');
  assert.match(f11.name,/骷髏王/);
  assert.equal(f11.model3d.file,boss.model3d.file);
  assert.equal(context.makeBoss(51).npcId,'tower_boss_1','51 層起從第 1 關那列重新輪');
});
